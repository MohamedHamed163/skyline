// Location names live in the locations table, so seed rows only carry the location id.
type SeedProperty = Omit<Property, "locationName">;
type SeedInput = Omit<
  SeedProperty,
  "previousStatus" | "adminNotes" | "createdAt" | "updatedAt" | "purpose" | "featured" | "floor" | "documents" | "bookedDates" | "developerDescription" | "weekendPrice" | "priceRules" | "hostId" | "pendingEdit" | "editOutcome" | keyof UnitRanges
> & Partial<UnitRanges> & {
  age: number;
  featured?: boolean;
  floor?: number;
  developerDescription?: string;
};

const property = ({ age, featured = false, floor, developerDescription = "", ...p }: SeedInput): SeedProperty => ({
  // No unit ranges unless the sample sets them (docs/unit-ranges.md).
  areaMax: null,
  bedroomsMax: null,
  bathroomsMax: null,
  floorMax: null,
  priceMax: null,
  ...p,
  featured,
  floor: floor ?? null,
  developerDescription,
  documents: [],
  bookedDates: [],
  weekendPrice: null,
  priceRules: [],
  purpose: "sale",
  // Sample sellers have no host account (docs/host-accounts.md).
  hostId: null,
  pendingEdit: null,
  editOutcome: null,
  previousStatus: p.status === "pending" ? null : "pending",
  adminNotes: "",
  createdAt: daysAgo(age),
  updatedAt: daysAgo(Math.max(age - 1, 0)),
});

